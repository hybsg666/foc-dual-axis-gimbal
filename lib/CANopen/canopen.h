#ifndef CANOPEN_H
#define CANOPEN_H

#include <Arduino.h>

// ============================================================
// 最小 CANopen 从站（CiA 301 的"通信子集"）
//
// 第 1 步只做三件事，够你把 CANopen 的骨架摸清：
//   · NMT       —— 网络管理：主站用 0x000 命令你 start / stop / 进预操作
//   · 心跳      —— 0x700+节点号，每 hb_period 毫秒报一次自己的状态
//   · SDO       —— 0x600+节点号 请求 / 0x580+节点号 应答，读写"对象字典"
//
// 对象字典里暂时只有身份类对象（0x1000 / 0x1001 / 0x1017 / 0x1018），
// 目的是让 SDO 通路先跑通；运动相关对象（0x6040 / 0x607A / 0x6064…）第 2、3 步再加。
//
// 节点号：1 = M0(yaw)，2 = M1(pitch)
// ============================================================

#define CO_NODE_M0 1
#define CO_NODE_M1 2

// 初始化：两个节点各发一次 Boot-up(0x00)，进入预操作态
void co_init();

// 每 loop 调用：发心跳
void co_update();

// 收到一帧就交给它。返回 true = 这帧被 CANopen 消费了
bool co_on_frame(uint32_t can_id, const uint8_t* data, uint8_t len);

// 板内"假主站"自检：不接任何主站硬件也能验证协议栈
// 做法：MCP2515 切到内部回环模式，自己发的帧自己收回来，走的是同一条协议栈
// 返回通过的检查项数（共 5 项）
int co_self_test();

// 手动当一次主站：hex 是空格分隔的十六进制字节串（形如 "40 00 10 00"）。
// 会临时切回环、发到 0x600+节点、打印收到的 0x580+节点应答，然后切回正常模式。
//   "r"  / "r2"  → 预置成"读 0x6064 实际位置"（M0 / M1），不用拼字节
//   "l"          → 切换解码注解开关（关 = 只打原始帧）
void co_manual_sdo(const char* hex);

#endif
